'use strict';
/**
 * Exports the certificates and research articles for import into WordPress,
 * and generates the plugin's icon file.
 *
 *   node tools/export-wp-content.js
 *
 * Output:
 *   wordpress/content/coa.json                     12 certificates, one object per lot
 *   wordpress/content/articles.json                8 articles + their meta
 *   wordpress/content/articles/<slug>.html         each article's prose, for post_content
 *   wordpress/plugins/pph-core/inc/icons.php       generated from src/art.js
 *
 * The icon file is generated rather than transcribed. There are 38 inline SVGs
 * and hand-copying them into PHP is a guaranteed source of silent diffs.
 */

const fs = require('fs');
const path = require('path');

const { icons, articlePhoto } = require('../src/art');
const { products, lots, articles } = require('../src/data');
const research = require('../src/pages/research');

const ROOT = path.join(__dirname, '..');
const CONTENT = path.join(ROOT, 'wordpress', 'content');
const PLUGIN_INC = path.join(ROOT, 'wordpress', 'plugins', 'pph-core', 'inc');

const UPLOAD_BASE = '/wp-content/uploads/pph';
const THEME_ASSETS = '/wp-content/themes/pph-child/assets';

/* Same rewrite the page and theme exporters use, so every layer agrees. */
function rewriteAssets(html) {
  return String(html)
    .replace(/(["'(])\/img\//g, `$1${THEME_ASSETS}/img/`)
    .replace(/(["'(])\/doc\//g, `$1${UPLOAD_BASE}/doc/`)
    .replace(/(["'(])\/video\//g, `$1${UPLOAD_BASE}/video/`);
}

fs.mkdirSync(path.join(CONTENT, 'articles'), { recursive: true });
fs.mkdirSync(PLUGIN_INC, { recursive: true });

/* ------------------------------------------------------------------ icons */

const iconEntries = Object.entries(icons)
  .map(([k, v]) => `\t${JSON.stringify(k)} => ${phpString(v)},`)
  .join('\n');

function phpString(s) {
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

fs.writeFileSync(
  path.join(PLUGIN_INC, 'icons.php'),
  `<?php
/**
 * Generated by tools/export-wp-content.js - do not edit.
 * Source: src/art.js
 *
 * The same inline SVGs the static build uses. Echoed raw, never escaped -
 * they are our own markup, not user input.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

function pph_icons() {
	return array(
${iconEntries}
	);
}

function pph_icon( $name ) {
	$all = pph_icons();
	return isset( $all[ $name ] ) ? $all[ $name ] : '';
}
`,
  'utf8'
);

/* ----------------------------------------------------------- certificates */

const documented = lots.filter((l) => l.doc);

const coa = documented.map((l) => {
  const p = products.find((x) => x.slug === l.slug) || null;
  return {
    lot: l.lot,
    slug: l.lot.toLowerCase(),
    product: l.product,
    product_slug: l.slug,
    size: l.size,
    date: l.date,
    received: l.received || '',
    purity: l.purity || '',
    content: l.content || '',
    endotoxin: l.endotoxin || '',
    heavy_metals: l.heavyMetals || '',
    sterility: l.sterility || '',
    retention: l.retention || '',
    method: l.method || '',
    identity: l.identity || '',
    lab: l.lab || '',
    vendor: l.vendor || '',
    verify_url: l.verifyUrl || '',
    status: l.status || 'available',
    note: l.note || '',
    accession: l.accession || '',
    doc_url: l.doc ? l.doc.replace(/^\/doc\//, `${UPLOAD_BASE}/doc/`) : '',
    doc_type: l.docType || 'PDF',
    preview_url: `${UPLOAD_BASE}/doc/coa/preview/${l.lot.toLowerCase()}.jpg`,
    /* Denormalised from the product so a certificate page renders even if the
       product has not been created in WooCommerce yet. Re-imported whenever
       the product data changes. */
    cas: p ? p.cas : '',
    formula: p ? p.formula : '',
    mw: p ? p.mw : '',
  };
});

fs.writeFileSync(path.join(CONTENT, 'coa.json'), JSON.stringify(coa, null, 2) + '\n', 'utf8');

/* --------------------------------------------------------------- articles */

/* research.js keeps each article's prose in a private BODIES table and only
   exposes it through articlePage(). Pull it back out of the rendered page
   rather than widening that module's public surface. */
function proseOf(a) {
  const html = research.articlePage(a);
  const open = '<div class="prose">';
  const i = html.indexOf(open);
  if (i === -1) throw new Error(`no prose block in ${a.slug}`);

  /* Walk to the matching </div> so a nested <div> inside the prose (figures
     carry one) does not truncate the body. */
  let depth = 1;
  let j = i + open.length;
  const re = /<\/?div\b[^>]*>/g;
  re.lastIndex = j;
  let m;
  while ((m = re.exec(html))) {
    depth += m[0][1] === '/' ? -1 : 1;
    if (depth === 0) return html.slice(j, m.index);
  }
  throw new Error(`unbalanced prose block in ${a.slug}`);
}

function refsOf(a) {
  const html = research.articlePage(a);
  const m = html.match(/<ol class="refs">([\s\S]*?)<\/ol>/);
  if (!m) return [];
  return Array.from(m[1].matchAll(/<span>([\s\S]*?)<\/span>/g)).map((x) => x[1].trim());
}

const articleMeta = articles.map((a) => {
  const prose = rewriteAssets(proseOf(a)).trim();
  fs.writeFileSync(path.join(CONTENT, 'articles', a.slug + '.html'), prose + '\n', 'utf8');
  return {
    slug: a.slug,
    title: a.title,
    category: a.category,
    date: a.date,
    date_label: a.dateLabel,
    read_time: a.readTime,
    author: a.author,
    role: a.role,
    excerpt: a.excerpt,
    abstract: a.abstract,
    tags: a.tags || [],
    featured: !!a.featured,
    refs: refsOf(a),
    /* The lead photograph's markup, rendered by src/art.js. Stored rather than
       reimplemented in PHP - photo() picks sizes and alt text and there is no
       value in having two copies of that logic. */
    lead_html: rewriteAssets(articlePhoto(a.slug)),
    file: a.slug + '.html',
    bytes: Buffer.byteLength(prose),
  };
});

fs.writeFileSync(
  path.join(CONTENT, 'articles.json'),
  JSON.stringify(articleMeta, null, 2) + '\n',
  'utf8'
);

/* ------------------------------------------------------------------ check */

const bad = [];

for (const c of coa) {
  for (const k of ['lot', 'product', 'date', 'purity', 'lab', 'doc_url']) {
    if (!c[k]) bad.push(`coa ${c.lot}: empty ${k}`);
  }
  if (!/^\/wp-content\//.test(c.doc_url)) bad.push(`coa ${c.lot}: doc_url not rewritten`);
}

for (const a of articleMeta) {
  if (!a.bytes) bad.push(`article ${a.slug}: empty body`);
  const body = fs.readFileSync(path.join(CONTENT, 'articles', a.file), 'utf8');
  if (!/<h2 id="s1"/.test(body)) {
    bad.push(`article ${a.slug}: no <h2 id="s1"> - the table of contents is built from those`);
  }
  if (/(["'(])\/(img|doc|video)\//.test(body)) bad.push(`article ${a.slug}: unrewritten asset path in body`);
  if (/(["'(])\/(img|doc|video)\//.test(a.lead_html)) bad.push(`article ${a.slug}: unrewritten asset path in lead_html`);
}

if (coa.length !== 12) bad.push(`expected 12 certificates, got ${coa.length}`);
if (articleMeta.length !== 8) bad.push(`expected 8 articles, got ${articleMeta.length}`);

if (bad.length) {
  console.error('Content export failed:\n  ' + bad.join('\n  '));
  process.exit(1);
}

console.log(
  `Exported ${coa.length} certificates and ${articleMeta.length} articles to wordpress/content/\n` +
    `Generated inc/icons.php (${Object.keys(icons).length} icons)\n` +
    `Import with: wp eval-file tools/import-wp-content.php --user=1`
);
