'use strict';
/**
 * Generates the pph-child theme's chrome and copies its assets.
 *
 *   node tools/export-wp-theme.js
 *
 * Writes (generated - do not hand-edit these four):
 *   wordpress/themes/pph-child/header.php       shell + utility strip + header + mega menu + <main>
 *   wordpress/themes/pph-child/footer.php       </main> + footer + mobile nav + overlays + age gate
 *   wordpress/themes/pph-child/front-page.php   the home page
 *   wordpress/themes/pph-child/404.php          the not-found page
 *   wordpress/themes/pph-child/assets/          css, js, img
 *   wordpress/uploads/pph/                      doc/ and video/, for wp-content/uploads/pph/
 *
 * Hand-written and NOT touched by this script: style.css, functions.php,
 * page.php, index.php.
 *
 * THE THEME FOLDER MUST BE NAMED `pph-child`. Asset paths are baked into the
 * imported page content as literal URLs, and content cannot run PHP to look the
 * path up. Rename the folder and every image breaks.
 */

const fs = require('fs');
const path = require('path');

const layout = require('../src/layout');
const home = require('../src/pages/home');
const S = require('../src/pages/static');

const ROOT = path.join(__dirname, '..');
const THEME = path.join(ROOT, 'wordpress', 'themes', 'pph-child');
const UPLOADS = path.join(ROOT, 'wordpress', 'uploads', 'pph');

const THEME_ASSETS = '/wp-content/themes/pph-child/assets';
const UPLOAD_BASE = '/wp-content/uploads/pph';

const GENERATED = '<?php\n/**\n * Generated by tools/export-wp-theme.js - do not edit.\n * Source: src/layout.js\n */\n';

/* Same rewrite the page exporter uses, so content and chrome agree. */
function rewriteAssets(html) {
  return html
    .replace(/(["'(])\/img\//g, `$1${THEME_ASSETS}/img/`)
    .replace(/(["'(])\/doc\//g, `$1${UPLOAD_BASE}/doc/`)
    .replace(/(["'(])\/video\//g, `$1${UPLOAD_BASE}/video/`);
}

function mainBody(fullPage) {
  const open = '<main id="main">';
  const a = fullPage.indexOf(open);
  const b = fullPage.lastIndexOf('</main>');
  if (a === -1 || b === -1) throw new Error('no <main id="main"> in page');
  return rewriteAssets(fullPage.slice(a + open.length, b)).trim();
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, e.name);
    const dst = path.join(to, e.name);
    if (e.isDirectory()) copyDir(src, dst);
    else fs.copyFileSync(src, dst);
  }
}

/* ------------------------------------------------------------------- run */

fs.mkdirSync(THEME, { recursive: true });

/* header.php ------------------------------------------------------------ */
/* `active` marks the current nav item. It needs the WordPress query to know
   which page we are on, so phase 1 ships without it - the nav works, the
   current item just is not underlined. Becomes dynamic when the mega menu
   starts querying WooCommerce terms at phase 4. */
const headerHtml = fixAccountLinks(stripQuickOrderLink(rewriteAssets(layout.header(null))));

/* WordPress only: the header's "Quick order" icon linked to /products/#quick-order,
   which no longer exists there (bulk-paste ordering was dropped from the WP
   products page - it stays a static-build-only feature, see
   wordpress/plugins/pph-core/inc/wc-helpers.php's archive-product.php note).
   Not touching src/layout.js for this - that file is shared with the static
   build via build.js, and the static site keeps quick order, so it keeps this
   link. */
function stripQuickOrderLink(html) {
  return html.replace(/[ \t]*<a class="iconbtn iconbtn--optional" href="\/products\/#quick-order">.*?<\/a>\n?/s, '');
}

/* WordPress only: /account/, /orders/ and /login/ were flat static-build
   pages (account.html, orders.html, login.html) - real files, real paths.
   On WordPress there is no post/page at any of those three paths: WooCommerce
   auto-creates its My Account page at /my-account/ (or wherever the "myaccount"
   page is actually set - the slug is not guaranteed to be the literal string
   "my-account"), login is a tab on that same page rather than its own URL, and
   "orders" is one of My Account's endpoints, not a top-level page. Every one of
   these five links (header masthead's Account icon, header utility bar's
   Orders/Wishlist/Sign in, footer's Order tracking, mobile nav's Sign in) was
   carrying the literal static-build path straight through, unrewritten -
   which 404s on a live WordPress install. form-checkout.php already does this
   correctly for its own "Sign in" link (wc_get_page_permalink('myaccount'));
   this extends the same pattern to the site-wide chrome, which - unlike that
   one hand-written template - is generated text with no PHP function calls of
   its own to fix at the source. Not touched in src/layout.js: that file is
   shared with the static build, where these ARE real flat pages and the
   literal paths are correct. */
function fixAccountLinks(html) {
  const myAccount = "<?php echo esc_url( wc_get_page_permalink( 'myaccount' ) ); ?>";
  const orders = "<?php echo esc_url( wc_get_account_endpoint_url( 'orders' ) ); ?>";
  return html
    .split('href="/account/#wishlist"').join(`href="${myAccount}#wishlist"`)
    .split('href="/account/"').join(`href="${myAccount}"`)
    .split('href="/orders/"').join(`href="${orders}"`)
    .split('href="/login/"').join(`href="${myAccount}"`);
}

fs.writeFileSync(
  path.join(THEME, 'header.php'),
  GENERATED +
    `?><!doctype html>
<html <?php language_attributes(); ?>>
<head>
<meta charset="<?php bloginfo( 'charset' ); ?>">
<meta name="viewport" content="width=device-width, initial-scale=1">
<script>document.documentElement.classList.add('has-js')</script>
<?php wp_head(); ?>
</head>
<body <?php body_class( 'pph' ); ?>>
<a class="skip-link" href="#main">Skip to main content</a>
${headerHtml}
<main id="main">
`,
  'utf8'
);

/* footer.php ------------------------------------------------------------ */
const footerHtml = fixAccountLinks(rewriteAssets(layout.footer()));

/* mobileNav() and overlays() are not exported from src/layout.js - they are
   emitted only inside page(). Take them from a rendered page rather than
   widening the static build's public surface for our convenience. */
const sample = S.privacy();
const afterFooter = sample.slice(sample.lastIndexOf('</footer>') + '</footer>'.length);
const chromeTail = fixAccountLinks(rewriteAssets(
  afterFooter.slice(0, afterFooter.indexOf('<script src=')).trim()
));

fs.writeFileSync(
  path.join(THEME, 'footer.php'),
  GENERATED +
    `?></main>
${footerHtml}
${chromeTail}
<?php wp_footer(); ?>
</body>
</html>
`,
  'utf8'
);

/* front-page.php and 404.php -------------------------------------------- */
for (const [file, fn] of [['front-page.php', home], ['404.php', S.notFound]]) {
  fs.writeFileSync(
    path.join(THEME, file),
    GENERATED + `get_header();\n?>\n${mainBody(fn())}\n<?php\nget_footer();\n`,
    'utf8'
  );
}

/* assets ---------------------------------------------------------------- */
const A = path.join(THEME, 'assets');
fs.rmSync(A, { recursive: true, force: true });
copyDir(path.join(ROOT, 'public', 'css'), path.join(A, 'css'));
copyDir(path.join(ROOT, 'public', 'js'), path.join(A, 'js'));
copyDir(path.join(ROOT, 'public', 'img'), path.join(A, 'img'));

/* catalogue.js is generated by build.js, not stored in public/. The cart,
   wishlist, quick-order and search suggest all need it. */
const catalogue = path.join(ROOT, 'site', 'js', 'catalogue.js');
if (!fs.existsSync(catalogue)) {
  console.error('site/js/catalogue.js is missing - run `npm run build` first.');
  process.exit(1);
}
fs.copyFileSync(catalogue, path.join(A, 'js', 'catalogue.js'));

/* uploads: the client's own documents and the hero video ----------------- */
fs.rmSync(UPLOADS, { recursive: true, force: true });
copyDir(path.join(ROOT, 'public', 'doc'), path.join(UPLOADS, 'doc'));
copyDir(path.join(ROOT, 'public', 'video'), path.join(UPLOADS, 'video'));

/* check ----------------------------------------------------------------- */
const bad = [];
for (const f of ['header.php', 'footer.php', 'front-page.php', '404.php']) {
  const t = fs.readFileSync(path.join(THEME, f), 'utf8');
  if (/(["'(])\/(img|doc|video)\//.test(t)) bad.push(`${f}: unrewritten asset path`);
  if (/href="[a-z0-9-]+\.html"/i.test(t)) bad.push(`${f}: flat .html link`);
}
if (!fs.readFileSync(path.join(THEME, 'footer.php'), 'utf8').includes('data-agegate')) {
  bad.push('footer.php: age gate missing - it is an AllayPay condition, not decoration');
}
if (bad.length) {
  console.error('Theme export failed:\n  ' + bad.join('\n  '));
  process.exit(1);
}

console.log(
  'Wrote header.php, footer.php, front-page.php, 404.php + assets to wordpress/themes/pph-child/\n' +
    'Staged doc/ and video/ in wordpress/uploads/pph/\n' +
    'Hand-written files (style.css, functions.php, page.php, index.php) were left alone.'
);
